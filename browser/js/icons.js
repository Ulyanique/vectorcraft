function mask(file, size) {
  return `<i class="ic" style="--icon:url(/assets/icons/${file}.svg);width:${size}px;height:${size}px"></i>`;
}

export function icon(name, size = 16) {
  if (name === "discord") {
    return `<svg viewBox="0 0 16 16" width="${size}" height="${size}" fill="currentColor"><path d="M6.1 5.4c.7-.3 1.4-.5 1.9-.6.5.1 1.2.3 1.9.6M4.6 11.2c.9.6 1.9.9 3.4.9s2.5-.3 3.4-.9"/><path d="M6.2 8.2v1.1M9.8 8.2v1.1" fill="none" stroke="currentColor" stroke-width="1.2" stroke-linecap="round"/></svg>`;
  }
  if (name === "selection" || name === "directSelection") {
    const fill = name === "selection" ? "#111" : "#fff";
    return `<span class="ic-stack" style="width:${size}px;height:${size}px"><i class="ic" style="--icon:url(/assets/icons/dc-arrow-fill.svg);background:${fill};width:${size}px;height:${size}px"></i>${mask(FILE[name], size)}</span>`;
  }
  const file = FILE[name] || name;
  return mask(file, size);
}
